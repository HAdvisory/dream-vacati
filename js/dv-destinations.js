  // ── DV_BY_ISO: reverse index ───────────────────────────────────────────
  // ISO → first destination registered with that ISO code.
  // Where multiple destinations share an ISO (e.g. IT: rome/capri/positano/lake-como/tuscany;
  // GR: santorini/mykonos/zakynthos; MX: cancun/mexico-city/oaxaca), the first slug
  // in DESTS wins. Use getDVDestinationBySlug() for sub-destinations.
  var BY_ISO = {};
  Object.keys(DESTS).forEach(function (slug) {
    var d = DESTS[slug];
    if (d.iso && !BY_ISO[d.iso]) {
      BY_ISO[d.iso] = d;
    }
  });

  // ── Public API ─────────────────────────────────────────────────────────

  global.DV_DESTINATIONS = DESTS;
  global.DV_BY_ISO       = BY_ISO;

  global.getDVDestinationBySlug = function (slug) {
    return DESTS[slug] || null;
  };

  global.getDVDestinationByISO = function (iso) {
    if (!iso) { return null; }
    return BY_ISO[iso.toUpperCase()] || null;
  };

  // ── validateDVDestinations() ───────────────────────────────────────────
  // Call from browser console: validateDVDestinations()
  // Returns { ok: boolean, warnings: string[], errors: string[] }
  global.validateDVDestinations = function () {
    var warnings = [];
    var errors   = [];
    var slugs    = Object.keys(DESTS);

    slugs.forEach(function (slug) {
      var d = DESTS[slug];

      if (d.slug !== slug) {
        errors.push(slug + ': slug field "' + d.slug + '" does not match object key');
      }

      ['name','country','region','emoji'].forEach(function (f) {
        if (!d[f]) { errors.push(slug + ': missing required field "' + f + '"'); }
      });

      ['crowdScore','budgetPressure'].forEach(function (f) {
        if (d[f] !== null && (d[f] < 1 || d[f] > 10)) {
          errors.push(slug + ': ' + f + ' out of range [1–10]: ' + d[f]);
        }
      });

      if (!Array.isArray(d.bestMonths)) {
        errors.push(slug + ': bestMonths must be an array');
      }

      if (d.iso === null && d.mapRegion !== null) {
        warnings.push(slug + ': iso is null but mapRegion is "' + d.mapRegion + '" — SVG cannot highlight this destination');
      }

      if (d.guideUrl && d.guideUrl[0] !== '/') {
        warnings.push(slug + ': guideUrl "' + d.guideUrl + '" should be root-relative (start with /)');
      }

      if (d.dailyCostMid !== null && d.dailyCostMid <= 0) {
        errors.push(slug + ': dailyCostMid must be a positive number');
      }

      if (d.worldCupHostCountry && !d.iso) {
        warnings.push(slug + ': worldCupHostCountry is true but iso is null');
      }
    });

    // Verify expected ISOs are indexed (dv-map-highlight.js COLOR_PRIMARY keys)
    var mapISOs = ['JM','JP','GR','ID','TH','MX','US','CA','IS','NZ','FR','IT','VN','CR'];
    mapISOs.forEach(function (iso) {
      if (!BY_ISO[iso]) {
        warnings.push('DV_BY_ISO: expected map ISO "' + iso + '" not indexed — add a destination with iso: "' + iso + '"');
      }
    });

    var ok = errors.length === 0;
    if (ok && warnings.length === 0) {
      console.log('[dv-destinations] Validation passed — ' + slugs.length + ' destinations, 0 errors, 0 warnings.');
    } else {
      if (errors.length)   { console.error('[dv-destinations] ' + errors.length + ' ERROR(S):\n  ' + errors.join('\n  ')); }
      if (warnings.length) { console.warn('[dv-destinations]  ' + warnings.length + ' WARNING(S):\n  ' + warnings.join('\n  ')); }
    }
    return { ok: ok, errors: errors, warnings: warnings };
  };

